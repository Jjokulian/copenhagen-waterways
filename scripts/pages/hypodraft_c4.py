def main(argv):
    try:
        page = text()
    except live.Unjustified as e:
        print(e, file=sys.stderr)
        return 1
    return 0 if draftkit.build(REL, page) is not None else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
