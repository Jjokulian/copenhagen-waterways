#!/usr/bin/env python3
"""docs/hypodrafts/C4.md - what the data held here can and cannot show about C4.

Every number is read from data or from a pinned document as the page is built, or
is a stated design value with its reason; every assertion is a checked claim
(LIVE_NUMBERS.md section 11), registered in data/manual/claims.d/w3-cc.json with
what it rests on. What the draft once said and could not justify is in
docs/ARCHIVE.md, not here. Before writing, the generator checks the two things
the page says of files no derived output describes: that the monthly panel's
binary file is exactly the layout its .json declares, and the span and
completeness of the Baltic wind files. The page is written through
scripts/pages/draftkit.py.

    python3 scripts/pages/hypodraft_c4.py
"""
import json
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))
import draftkit
import live
from common import ROOT

C = live.claim
REL = "docs/hypodrafts/C4.md"
# the depth the published inflow statistics read the eastern Gotland Basin at
DEPTH = "{read:CC-MOHRHOLZ-2018:200|the eastern Gotland Basin (200 m)}"
WIND = [os.path.join(ROOT, "data", "raw", "marine", f"wind_baltic_{p}.json") for p in "ncs"]


def refuse(msg):
    raise live.Unjustified("C4: " + msg)


def check_series():
    """The page says the .bin is exactly the layout the .json declares: each
    variable's block - station and month indices as uint16, values as float32,
    as its _layout says - starts where the previous one ends, and the last ends
    at the end of the file."""
    base = os.path.join(ROOT, "docs", "data", "areas")
    s = json.load(open(os.path.join(base, "stations_series.json"), encoding="utf-8"))
    if "uint16 station" not in s["_layout"] or "float32 values" not in s["_layout"]:
        refuse("stations_series.json no longer declares the layout the check assumes")
    point = struct.calcsize("<HHf")
    at = 0
    for v in s["variables"]:
        if v["offset"] != at:
            refuse(f"stations_series.bin: {v['key']} does not start where the block before it ends")
        at += v["n"] * point
    if at != os.path.getsize(os.path.join(base, "stations_series.bin")):
        refuse("stations_series.bin is not exactly as long as the layout its .json declares")


def wind_span():
    """First and last hour of the Baltic wind files, refusing the page if they
    disagree with each other or any speed or direction is missing."""
    spans = set()
    for f in WIND:
        h = json.load(open(f, encoding="utf-8"))["hourly"]
        for k in ("wind_speed_10m", "wind_direction_10m"):
            if len(h[k]) != len(h["time"]) or any(x is None for x in h[k]):
                refuse(f"{os.path.basename(f)}: {k} has a missing value")
        spans.add((h["time"][0], h["time"][-1]))
    if len(spans) != 1:
        refuse(f"the Baltic wind files cover different spans: {sorted(spans)}")
    return spans.pop()


